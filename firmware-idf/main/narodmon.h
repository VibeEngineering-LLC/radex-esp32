/**
 * Выгрузка показаний на narodmon.ru (#RADEX-8).
 * ВЫКЛЮЧЕНА ПО УМОЛЧАНИЮ И ПОСЛЕ КАЖДОЙ ПЕРЕЗАГРУЗКИ.
 * Признак «включено» намеренно НЕ сохраняется в энергонезависимую память: в NVS
 * живут только адрес станции и интервал. Сброс, пропадание питания, обновление
 * прошивки — всё возвращает выгрузку в выключенное состояние. Включение всегда
 * остаётся явным действием человека; ни перезагрузка, ни восстановление после
 * сбоя не должны возобновить отправку сами.
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>

/**
 * Инициализирует модуль выгрузки, читает настройки из NVS.
 * Отправку НЕ включает.
 */
void narodmon_start(void);

/**
 * Выполняет одну попытку отправки данных на сервер.
 * Молчит, если выключено, не задана станция, нет Wi-Fi или данные невалидны.
 */
void narodmon_publish(void);

/**
 * Возвращает текущее состояние включения выгрузки.
 */
bool narodmon_is_enabled(void);

/**
 * Включает или выключает выгрузку в текущей сессии.
 * Не сохраняет состояние в NVS.
 */
bool narodmon_set_enabled(bool on);

/**
 * Устанавливает конфигурацию: MAC-адрес станции и интервал отправки (в минутах).
 * Адрес должен быть в формате AA:BB:CC:DD:EE:FF.
 * Интервал не может быть меньше 5 минут.
 */
bool narodmon_set_config(const char *station_mac, int interval_min);

/**
 * Записывает текущую конфигурацию в JSON-формате в буфер.
 * Возвращает длину строки (без завершающего нуля) или отрицательное значение при ошибке.
 */
int narodmon_config_json(char *buf, size_t len);
