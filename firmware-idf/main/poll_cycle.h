#pragma once

#include <stdbool.h>
#include <stdint.h>
#include <stddef.h>
#include <time.h>

/**
 * Инициализация модуля цикла измерений.
 * Читает ручную настройку цикла из NVS.
 */
void poll_cycle_init(void);

/**
 * Обработка нового значения радона.
 * Возвращает true, если значение новое (не повтор),
 * и false, если прибор ещё не пересчитал (повтор).
 * При возвращении false вызывающий код не должен записывать точку в историю.
 */
bool poll_cycle_observe(time_t ts, float radon);

/**
 * Возвращает оценённый цикл измерений в минутах.
 * Возвращает 0, если цикл ещё не определён.
 */
uint32_t poll_cycle_minutes(void);

/**
 * Возвращает задержку до следующего опроса в миллисекундах.
 * Учитывает цикл и добавляет минуту запаса от момента последнего обновления.
 */
uint32_t poll_cycle_next_delay_ms(void);

/**
 * Ручная установка цикла измерений в минутах.
 * Если minutes = 0, возвращается автоопределение.
 */
void poll_cycle_set_manual(uint32_t minutes);

/**
 * Записывает состояние модуля в JSON-формате в буфер.
 * Возвращает количество записанных символов (без завершающего нуля).
 */
int poll_cycle_json(char *buf, size_t len);
