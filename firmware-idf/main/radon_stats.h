/**
 * История показаний радона на флеш-памяти, средние за периоды и оценка соответствия
 * помещений нормативу по рациональному методу.
 *
 * Источник методики: «Оценка соответствия помещений зданий требованиям Норм радиационной
 * безопасности по ограничению содержания радона в воздухе. Методика радиационного контроля
 * (проект)», АНРИ, 2025, №1(120), с. 76–95; практическое руководство — Цапалов А.А. и др.
 *
 * Все величины — по объёмной активности (ОА) радона, Бк/м³. Нормативы РФ по ОА:
 * 200 для новых и реконструированных зданий, 400 для эксплуатируемых (в НРБ-99/2009 они
 * заданы по ЭРОА вдвое меньшими значениями, при факторе равновесия 0,5).
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <time.h>

/**
 * Структура для хранения статистики за период.
 * mean — среднее значение ОА радона за период, Бк/м³.
 * points — количество измерений.
 * coverage — доля периода, покрытая измерениями (0..1).
 * span_sec — фактически охваченный срок в секундах.
 * valid — признак достаточности данных для достоверной оценки.
 */
typedef struct {
    float    mean;
    uint32_t points;
    float    coverage;
    uint32_t span_sec;
    bool     valid;
} radon_period_t;

/**
 * Результат оценки соответствия нормативу.
 * TOO_SHORT — измерение слишком короткое.
 * COMPLIES — соответствует нормативу.
 * EXCEEDS — превышает норматив.
 * UNCERTAIN — неопределённый результат («серая зона»).
 */
typedef enum {
    RADON_VERDICT_TOO_SHORT = 0,
    RADON_VERDICT_COMPLIES,
    RADON_VERDICT_EXCEEDS,
    RADON_VERDICT_UNCERTAIN
} radon_verdict_t;

/**
 * Результат оценки соответствия помещений нормативу.
 * verdict — итоговая оценка.
 * c — среднее значение ОА радона за период, Бк/м³.
 * uv — временная неопределённость по таблице методики.
 * kp — коэффициент кратности (−1, если не определён в ограниченном режиме вентиляции).
 * crit1, crit2 — вычисленные значения критериев.
 * days — длительность измерения в сутках.
 * c_rl — применённый норматив (Бк/м³).
 * restricted — режим вентиляции: true — окна и двери постоянно закрыты.
 * u_d_eff — #RADEX-91: ФАКТИЧЕСКИ применённая инструментальная
 *   неопределённость (доля, k=2) — та, что реально вошла в crit1/crit2, ПОСЛЕ
 *   поднятия до 0.2, если введённое значение было меньше. Раньше эта поправка
 *   происходила молча на локальной переменной внутри radon_stats_assess_range
 *   и наружу не отдавалась вообще — на странице введённое число (например,
 *   0.15) выглядело как использованное, хотя расчёт шёл по 0.2. Ноль — оценка
 *   не дошла до применения u_d (verdict остался too_short раньше клампа).
 */
typedef struct {
    radon_verdict_t verdict;
    float    c;
    float    uv;
    float    kp;
    float    crit1;
    float    crit2;
    uint32_t days;
    float    c_rl;
    bool     restricted;
    float    u_d_eff;
} radon_assess_t;

/**
 * Инициализация модуля.
 * Возвращает true при успешной инициализации.
 */
bool radon_stats_init(void);

/* #RADEX-172. Файл истории /data/radon.csv ПИШЕТСЯ из задачи BLE-стека
   (колбэк измерения -> radon_stats_add) и ЧИТАЕТСЯ из задачи httpd
   (/api/history/range, /api/export.csv, /api/tests/points). Это разные задачи
   FreeRTOS, и до 01.09.2026 они ходили в файл без всякой синхронизации:
   читатель мог попасть на файл в момент прореживания (remove + rename).

   Все публичные функции модуля берут мьютекс сами. Пара lock/unlock нужна
   ТОЛЬКО web_server.c, который открывает radon_stats_file() своим fopen() в
   обход модуля. Мьютекс РЕКУРСИВНЫЙ: radon_stats_add() внутри зовёт
   radon_stats_test_start(), radon_stats_reset() — её же.
   lock вернул false — unlock вызывать НЕЛЬЗЯ. */
bool radon_stats_mutex_create(void);   /* зовётся из radon_stats_init() */
bool radon_stats_lock(uint32_t timeout_ms);
void radon_stats_unlock(void);
uint32_t radon_stats_lock_timeouts(void);   /* диагностика, в норме 0 */

/* #RADEX-172, вторая половина решения. Держать мьютекс всю потоковую отдачу
   (export/history_range) НЕЛЬЗЯ — измерено 01.09.2026: на файле 188 КБ и
   RSSI -88 дБм один экспорт занимает ~14 с, дольше таймаута писателя, и
   показание из BLE-задачи было ПОТЕРЯНО (lock_timeouts стал 1).

   Но длинному читателю мьютекс на всю отдачу и не нужен: штатный писатель
   только ДОПИСЫВАЕТ в конец, а дозапись читателю не вредит — он просто не
   увидит самых новых байт. Опасны лишь операции, которые файл ПЕРЕСОБИРАЮТ:
   прореживание при переполнении, radon_stats_compact(), radon_stats_reset(),
   radon_stats_start_test(). Каждая из них увеличивает счётчик поколения.

   Правило для читателя: запомнить поколение до начала отдачи и сверять его
   по ходу; изменилось — файл под нами пересобрали, ответ доотдавать нельзя,
   его надо оборвать. Так у писателя нет ожидания вовсе, а склеенного из двух
   разных файлов ответа не возникает. */
uint32_t radon_stats_generation(void);

/**
 * Добавление нового измерения в историю.
 * ts — метка времени измерения.
 * radon — значение ОА радона, Бк/м³.
 * radon_avg — среднее значение ОА радона за период, Бк/м³.
 * temp — температура воздуха, °C.
 * hum — относительная влажность, %.
 */
void radon_stats_add(time_t ts, float radon, float radon_avg, float temp, float hum);

/* #RADEX-113: перевести записи с относительными метками (отрицательные секунды
   от включения) в реальное время. Вызывать, когда часы стали известны.
   Возвращает число переведённых записей, 0 — переводить было нечего, -1 — сбой. */
int radon_stats_rebase(time_t now);

/**
 * Получение статистики за указанный период.
 * seconds_back — длительность периода в секундах.
 * out — указатель на структуру для записи результата.
 * Возвращает true при успешном получении данных.
 */
bool radon_stats_period(uint32_t seconds_back, radon_period_t *out);

/**
 * Оценка соответствия помещения нормативу.
 * c_rl — применённый норматив (Бк/м³).
 * u_d — неопределённость измерения.
 * restricted — режим вентиляции: true — окна и двери постоянно закрыты.
 * out — указатель на структуру для записи результата.
 */
void radon_stats_assess(float c_rl, float u_d, bool restricted, radon_assess_t *out);
/* То же, но по произвольному интервалу истории (0 — граница не задана). */
void radon_stats_assess_range(time_t from, time_t to,
                              float c_rl, float u_d, bool restricted,
                              radon_assess_t *out);
/* JSON одной оценки по интервалу — для маршрута /api/assess. */
int  radon_stats_assess_json(char *buf, size_t len, time_t from, time_t to,
                             float c_rl, float u_d, bool restricted);

/**
 * Формирование JSON-представления данных оценки.
 * buf — буфер для вывода.
 * len — длина буфера.
 * c_rl — применённый норматив (Бк/м³).
 * u_d — неопределённость измерения.
 * restricted — режим вентиляции: true — окна и двери постоянно закрыты.
 * Возвращает длину сформированной строки или -1 при ошибке.
 */
int  radon_stats_json(char *buf, size_t len, float c_rl, float u_d, bool restricted);

/**
 * Получение пути к файлу истории.
 * Возвращает указатель на строку с путём к файлу.
 */
const char *radon_stats_file(void);

/* #RADEX-174. Одна строка истории после разбора. w — ВЕС строки: сколько
   исходных измерений в неё вошло. У сырой записи 1; у строки после уплотнения
   (radon_stats_compact) — число свёрнутых измерений, записанное шестым полем.
   Суточная средняя из 25 измерений и одиночная точка — не одно и то же.

   Разбор строки живёт в ОДНОМ месте намеренно: тем же классом дефекта был
   #RADEX-173 (путь к файлу повторён строкой в одной функции из десяти). До
   этой правки шестое поле читали пять функций из десяти, и /api/history/range
   отдавал 5 «точек» там, где измерений был 71. */
typedef struct {
    time_t   ts;
    float    radon;
    float    radon_avg;
    float    temp;
    float    hum;
    uint32_t w;
} radon_row_t;

/* Разбор одной строки файла истории. false — строка не данные (заголовок,
   мусор, обрыв записи). Незаполненные поля получают NAN, вес — 1. */
bool radon_csv_parse(const char *line, radon_row_t *out);

/* #RADEX-174: приём истории извне (POST /api/history/import). Штатного способа
   вернуть выгруженный файл на плату не было вовсе, и после порчи истории
   01.09.2026 (#RADEX-173) выяснилось, что бэкап без способа восстановления —
   половина решения. Приём потоковый: begin() открывает временный файл, line()
   проверяет и пишет одну строку, commit() под мьютексом подменяет рабочий файл
   целиком. До commit() рабочая история не трогается: обрыв связи посреди
   загрузки оставляет старые данные на месте. */
bool radon_stats_import_begin(void);
bool radon_stats_import_line(const char *line);
int  radon_stats_import_commit(void);   /* принято строк данных, -1 — ошибка */
void radon_stats_import_abort(void);

/* #RADEX-224: тот же приём строк, но результат ложится ОТДЕЛЬНЫМ файлом замера
   /data/test_<первая метка>.csv, а общая история не меняется вовсе. Оператор:
   «анализируем ТОЛЬКО на вкладке графики». Возвращает начало импортированного
   замера (0 — неудача); rows_out (можно NULL) — сколько строк принято. */
time_t radon_stats_import_commit_as_test(int *rows_out);

// Последнее записанное значение радона (NAN, если записей нет).
// Нужно после перезагрузки: иначе первое значение примут за новое.
float radon_stats_last_radon(void);

// #RADEX-16 / #RADEX-102 (переработано 30.08, оператор: «каждый новый замер
// должен создавать отдельный файл на флеш», решение — разделить общую историю
// и замеры). Общий /data/radon.csv копит ВСЁ бессрочно (для «Показаний» и
// «Графиков» — интервал НЕ ограничен окном замера). Отдельно, при активном
// замере, каждая запись ДУБЛИРУЕТСЯ в свой файл /data/test_<tstart>.csv — путь
// вычисляется детерминированно из tstart, отдельного поля в NVS не заводим.
// radon_stats_reset() теперь удаляет ТОЛЬКО файл текущего замера — общая
// история для графиков не страдает (было наоборот: «Сброс» стирал всё).
bool   radon_stats_start_test(void);   // отметить начало теста «сейчас» + создать файл замера
bool   radon_stats_reset(void);        // удалить ФАЙЛ ЗАМЕРА и снять отметку (общую историю не трогает)
time_t radon_stats_test_start(void);

/* #RADEX-150: ЭФФЕКТИВНОЕ начало замера. Явная отметка (кнопка «Новый замер»)
   имеет приоритет; без неё возвращает метку ПЕРВОЙ записи истории — замер идёт
   по умолчанию, ручной клик на свежей плате и после «Сброса» не нужен. 0 —
   данных в истории ещё нет вовсе. Числа заключения от этого не меняются:
   radon_stats_assess_range() при from=0 уже считала длительность от первой
   записи (radon_stats.c:429), то есть «без отметки» и «с первой записи» —
   один и тот же расчёт. Всё, что пишет и удаляет ФАЙЛ замера
   (radon_stats_add, radon_stats_reset, radon_stats_tests_list_json),
   по-прежнему работает по ЯВНОЙ отметке radon_stats_test_start(): файла
   /data/test_<epoch>.csv у неявного замера нет и быть не должно — он
   дублировал бы всю общую историю. */
time_t radon_stats_test_start_eff(void);

/* Путь к файлу активного замера. Пишет в out путь вида "/data/test_<epoch>.csv",
   либо пустую строку, если замер не начат. out_sz — как минимум 40 байт. */
void radon_stats_test_file(time_t start, char *out, size_t out_sz);

/* #RADEX-102: список сохранённых замеров (прошлых и текущего) как JSON-массив
   в buf. Каждый элемент: start (epoch), points, span_sec, active (совпадает ли
   с текущим tstart). Возвращает длину строки либо -1 при переполнении buf. */
int radon_stats_tests_list_json(char *buf, size_t len);

/* #RADEX-227: заключение по ОДНОМУ сохранённому замеру — источником служит его
   файл /data/test_<start>.csv, а не общая история. Формат ответа тот же, что у
   radon_stats_assess_json. Возвращает длину строки, -1 при ошибке (в том числе
   если start не задан). */
int radon_stats_assess_test_json(char *buf, size_t len, time_t start,
                                 float c_rl, float u_d, bool restricted);

/* #RADEX-228: имя (метка) замера. Хранится отдельным реестром /data/labels.csv,
   а НЕ в имени файла: SPIFFS собран с CONFIG_SPIFFS_OBJ_NAME_LEN=32, а
   "/test_1788463052.csv" — уже 20 символов, и имя файла разбирается обратно в
   epoch. get возвращает длину (0 — имени нет), set принимает пустую строку как
   «снять имя»; допустимые символы — латиница, цифры, дефис, подчёркивание,
   остальное отбрасывается. */
int  radon_stats_test_label_get(time_t start, char *out, size_t out_sz);
bool radon_stats_test_label_set(time_t start, const char *label);

/* #RADEX-228: снять текущий замер в файл /data/test_<start>.csv — записи общей
   истории от начала замера. Нужно потому, что замер идёт по умолчанию (от
   первой записи истории), а файл создаёт только кнопка «Новый замер»: без
   снимка «Сохранить замер» было бы нечего сохранять. Возвращает начало
   сохранённого замера, 0 при неудаче; points_out (можно NULL) — сколько
   записей попало в файл. */
time_t radon_stats_test_snapshot(uint32_t *points_out);

/* #RADEX-234: удалить сохранённый замер — файл и имя. Идущий замер не удаляет
   (возвращает false): для него есть «Сброс», и обходить его подтверждение
   отдельной кнопкой в списке нельзя. */
bool radon_stats_test_delete(time_t start);

/* Содержимое ОДНОГО файла замера в формате точек — тот же JSON, что отдаёт
   /api/history/range, для переиспользования на странице (тот же парсер точек).
   start — epoch, которым назван файл (id замера). Возвращает длину либо -1,
   если файла с таким start не существует. */
int radon_stats_test_points_json(time_t start, char *buf, size_t len);
/* #RADEX-59: уплотнение истории по возрасту данных. Свежее raw_days суток —
   как есть, до hour_days — среднечасовые, старше — среднесуточные.
   Возвращает число строк после уплотнения либо -1. */
int radon_stats_compact(uint32_t raw_days, uint32_t hour_days);   // 0, если тест не начат

/* #RADEX-225: таблицы UV(t) и Kp(t) методики как JSON — странице нужен ход
   доверительного интервала ВО ВРЕМЕНИ, то есть UV для каждой длительности, а не
   только для текущей. Отдаём таблицу, а не считаем границы на плате: копия
   таблицы в JS разошлась бы с прошивкой при первой же правке (§33), а так
   источник один и тот же массив, что участвует в расчёте вердикта.
   Формат: {"normal":[[сут,uv,kp],…],"restricted":[[сут,uv,-1],…]}
   (у ограниченного режима Kp в методике не задан — отдаём -1).
   Возвращает длину либо -1, если не поместилось. */
int radon_stats_method_tables_json(char *buf, size_t len);

